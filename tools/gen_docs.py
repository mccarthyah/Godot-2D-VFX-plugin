#!/usr/bin/env python3
"""Generate the Markdown reference from the Sparkform sources.

Every table in ``docs/API.md`` and ``docs/EFFECTS.md`` is parsed straight out of
the ``##`` doc comments and the ``@export`` declarations in
``addons/sparkform``. That keeps the reference honest: if a property changes
name, type or default, the generated page changes with it.

Usage::

    python3 tools/gen_docs.py          # write the pages
    python3 tools/gen_docs.py --check  # exit 1 if the pages are out of date

CI runs the second form, so a code change that forgets the docs fails the
build instead of drifting silently.
"""

from __future__ import annotations

import argparse
import re
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ADDON = ROOT / "addons" / "sparkform"
API_PAGE = ROOT / "docs" / "API.md"
EFFECTS_PAGE = ROOT / "docs" / "EFFECTS.md"

BANNER = (
    "<!-- Generated by tools/gen_docs.py from the source. Do not edit by hand. -->\n"
)

EXPORT = re.compile(r"^@export(?!_group)")
VAR = re.compile(r"var (\w+):\s*([^=]+?)\s*(?:=\s*(.+))?$")
FUNC = re.compile(r"^(?:static )?func (\w+)\((.*?)\)(?:\s*->\s*([\w\[\]]+))?")

PERSISTENT = {
    "beam",
    "portal",
    "rune_circle",
    "shield_bubble",
    "tether",
    "trail",
    "vortex",
}


def doc_body(line: str) -> str:
    """The text of a ``##`` comment, keeping its indentation for code blocks."""
    body = line[2:]
    if body.startswith(" "):
        body = body[1:]
    return body.rstrip()


class Script:
    """The pieces of a GDScript file the reference needs."""

    def __init__(self, path: Path) -> None:
        self.path = path
        self.stem = path.stem
        text = path.read_text(encoding="utf-8").split("\n")
        self.class_name = ""
        self.extends = ""
        self.doc = ""
        self.members: list[dict] = []
        self.funcs: list[dict] = []
        self.signals: list[dict] = []
        self._parse(text)

    def _parse(self, lines: list[str]) -> None:
        header: list[str] = []
        group = ""
        i = 0
        while i < len(lines):
            line = lines[i]
            if line.startswith("class_name "):
                self.class_name = line.split()[1]
            elif line.startswith("extends "):
                self.extends = line[len("extends "):].strip().strip('"')
            elif line.startswith("##") and not header and not self.doc:
                block = []
                while i < len(lines) and lines[i].startswith("##"):
                    block.append(doc_body(lines[i]))
                    i += 1
                self.doc = bbcode("\n".join(block).strip())
                continue
            elif line.startswith("@export_group("):
                group = re.findall(r'"([^"]*)"', line)[0]
            elif line.startswith("signal "):
                name = line.split("(")[0].split()[1]
                doc = self._doc_above(lines, i)
                self.signals.append({"name": name, "doc": doc})
            elif EXPORT.match(line) or line.startswith("func ") or line.startswith("static func "):
                if EXPORT.match(line):
                    doc = self._doc_above(lines, i)
                    # A default can wrap: chain_lightning.points is a literal array.
                    declaration = line
                    while unbalanced(declaration):
                        i += 1
                        declaration += " " + lines[i].strip()
                    self.members.append(self._member(declaration, group, doc))
                else:
                    func = self._func(lines, i)
                    self.funcs.append(func)
                    while variant_signature_open(lines[i]):
                        i += 1
            i += 1

    @staticmethod
    def _doc_above(lines: list[str], index: int) -> str:
        block = []
        k = index - 1
        while k >= 0 and lines[k].startswith("##"):
            block.insert(0, doc_body(lines[k]))
            k -= 1
        return bbcode("\n".join(block).strip())

    @staticmethod
    def _member(line: str, group: str, doc: str) -> dict:
        match = VAR.search(line)
        if not match:
            raise SystemExit(f"cannot parse export at {line!r}")
        return {
            "group": group,
            "name": match.group(1),
            "type": match.group(2).strip(),
            "default": (match.group(3) or "").strip(),
            "doc": doc,
        }

    def _func(self, lines: list[str], index: int) -> dict:
        """Read a ``func`` declaration, joining wrapped argument lists."""
        doc = self._doc_above(lines, index)
        signature = lines[index]
        while variant_signature_open(signature):
            index += 1
            signature += " " + lines[index].strip()
        match = FUNC.match(signature)
        args = " ".join(match.group(2).split())
        ret = match.group(3) or ""
        return {
            "name": match.group(1),
            "args": args,
            "ret": ret,
            "signature": f"{match.group(1)}({args})" + (f" -> {ret}" if ret else ""),
            "doc": doc,
            "private": match.group(1).startswith("_"),
        }

    def public_funcs(self) -> list[dict]:
        return [f for f in self.funcs if not f["private"]]


def variant_signature_open(signature: str) -> bool:
    """True when a ``func`` line continues on the next line."""
    return signature.count("(") > signature.count(")")


def unbalanced(declaration: str) -> bool:
    """True when brackets are still open, i.e. the declaration continues."""
    return any(
        declaration.count(open_bracket) > declaration.count(close_bracket)
        for open_bracket, close_bracket in (("(", ")"), ("[", "]"), ("{", "}"))
    )


def bbcode(text: str) -> str:
    """Turn Godot's doc-comment BBCode into Markdown."""
    text = re.sub(
        r"\[codeblock\]\n?(.*?)\[/codeblock\]",
        lambda m: "\n```gdscript\n" + textwrap.dedent(m.group(1)).strip("\n") + "\n```\n",
        text,
        flags=re.S,
    )
    text = re.sub(r"\[code\](.*?)\[/code\]", r"`\1`", text, flags=re.S)
    text = re.sub(
        r"\[(?:member|method|signal|param|constant|enum|theme_item)\s+([^\]]+)\]",
        r"`\1`",
        text,
    )
    text = re.sub(r"\[b\](.*?)\[/b\]", r"**\1**", text, flags=re.S)
    text = re.sub(r"\[i\](.*?)\[/i\]", r"*\1*", text, flags=re.S)
    text = re.sub(r"\[url=([^\]]+)\](.*?)\[/url\]", r"[\2](\1)", text, flags=re.S)
    text = re.sub(r"\[url\](.*?)\[/url\]", r"\1", text, flags=re.S)
    return text


def anchor(text: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return slug


def table(headers: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |"]
    out.append("|" + "|".join("---" for _ in headers) + "|")
    for row in rows:
        out.append("| " + " | ".join(cell.replace("|", "\\|") for cell in row) + " |")
    return "\n".join(out)


def code_span(text: str) -> str:
    return f"`{text}`" if text else "`—`"


def prose(text: str) -> str:
    return text.replace("\n", " ") if text else "_No description yet._"


def property_tables(members: list[dict]) -> list[str]:
    blocks: list[str] = []
    current = None
    rows: list[list[str]] = []
    for member in members:
        if member["group"] != current:
            if rows:
                blocks.append(table(["Property", "Type", "Default", "Description"], rows))
                blocks.append("")
            current = member["group"]
            rows = []
            blocks.append(f"**{current or 'General'}**\n")
        rows.append(
            [
                code_span(member["name"]),
                code_span(member["type"]),
                code_span(member["default"]),
                prose(member["doc"]),
            ]
        )
    if rows:
        blocks.append(table(["Property", "Type", "Default", "Description"], rows))
        blocks.append("")
    return blocks


def load_scripts() -> dict[str, Script]:
    scripts = {}
    for path in sorted(ADDON.rglob("*.gd")):
        if path.name in {"plugin.gd"}:
            continue
        script = Script(path)
        scripts[script.stem] = script
    return scripts


def build_api(scripts: dict[str, Script]) -> str:
    spawner = scripts["sparkform"]
    effect_base = scripts["vfx_effect"]
    lines = [BANNER, "# Sparkform API reference", ""]
    lines.append(
        "Everything the addon exposes: the `Sparkform` autoload that spawns and "
        "recycles effects, and the base classes an effect script builds on. "
        "Property tables for the individual effects live in "
        "[EFFECTS.md](EFFECTS.md)."
    )
    lines.append("")

    lines.append("## Contents")
    lines.append("")
    lines.append("- [`Sparkform` autoload](#sparkform-autoload)")
    lines.append("- [Spawner summary](#spawner-summary)")
    for func in spawner.public_funcs():
        lines.append(f"  - [`{func['name']}`](#{anchor(func['name'])})")
    for name in ("vfx_effect", "vfx_streaks", "vfx_shapes"):
        if name in scripts:
            title = scripts[name].class_name or scripts[name].stem
            lines.append(f"- [`{title}`](#{anchor(title)})")
    lines.append("")

    lines.append('## `Sparkform` autoload')
    lines.append("")
    lines.append(spawner.doc)
    lines.append("")

    lines.append("### Signals")
    lines.append("")
    lines.append(
        table(
            ["Signal", "Description"],
            [[code_span(s["name"]), prose(s["doc"])] for s in spawner.signals],
        )
    )
    lines.append("")

    lines.append("### Settings")
    lines.append("")
    lines.extend(property_tables(spawner.members))
    lines.append("")

    lines.append("## Spawner summary")
    lines.append("")
    rows = []
    for func in spawner.public_funcs():
        rows.append(
            [
                code_span(func["name"]),
                code_span(func["args"] or "—"),
                code_span(func["ret"] or "void"),
                prose(func["doc"]).split(". ")[0].rstrip(".") + ".",
            ]
        )
    lines.append(table(["Method", "Arguments", "Returns", "Summary"], rows))
    lines.append("")

    for section, predicate in (
        ("Spawners", lambda f: f["name"] not in UTILITIES),
        ("Utilities", lambda f: f["name"] in UTILITIES),
    ):
        funcs = [f for f in spawner.public_funcs() if predicate(f)]
        if not funcs:
            continue
        lines.append(f"## {section}")
        lines.append("")
        for func in funcs:
            lines.append(f"### `{func['signature']}`")
            lines.append("")
            lines.append(f'<a id="{anchor(func["name"])}"></a>')
            lines.append("")
            lines.append(func["doc"] or "_No description yet._")
            lines.append("")

    for name in ("vfx_effect", "vfx_streaks", "vfx_shapes"):
        if name not in scripts:
            continue
        script = scripts[name]
        title = script.class_name or script.stem
        lines.append(f"## `{title}`")
        lines.append("")
        if script.extends:
            lines.append(f"Extends `{Path(script.extends).stem if script.extends.startswith('res://') else script.extends}`.")
            lines.append("")
        lines.append(script.doc or "_No description yet._")
        lines.append("")
        if script.signals:
            lines.append("### Signals")
            lines.append("")
            lines.append(
                table(
                    ["Signal", "Description"],
                    [[code_span(s["name"]), prose(s["doc"])] for s in script.signals],
                )
            )
            lines.append("")
        if script.members:
            lines.append("### Properties")
            lines.append("")
            lines.extend(property_tables(script.members))
            lines.append("")
        funcs = script.public_funcs()
        if funcs:
            lines.append("### Methods")
            lines.append("")
            for func in funcs:
                lines.append(f"#### `{func['signature']}`")
                lines.append("")
                lines.append(func["doc"] or "_No description yet._")
                lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def tidy(lines: list[str]) -> str:
    """Join a page and collapse runs of blank lines to a single one."""
    text = "\n".join(lines).rstrip() + "\n"
    while "\n\n\n" in text:
        text = text.replace("\n\n\n", "\n\n")
    return text


SPAWNER_ALIASES = {"chain": "chain_lightning", "shield": "shield_bubble"}
UTILITIES = {"spawn", "stop_all", "get_active_count", "get_persistent_count"}


def spawner_index(scripts: dict[str, Script]) -> dict[str, dict]:
    """Map effect stem -> the autoload method that spawns it."""
    index = {}
    for func in scripts["sparkform"].public_funcs():
        if func["name"] in UTILITIES:
            continue
        index[SPAWNER_ALIASES.get(func["name"], func["name"])] = func
    return index


def spawner_for(scripts: dict[str, Script], stem: str) -> dict:
    return spawner_index(scripts).get(stem, {})


def build_effects(scripts: dict[str, Script]) -> str:
    effects = [s for s in scripts.values() if s.path.parent.name == "effects"]
    effects.sort(key=lambda s: (s.stem in PERSISTENT, s.stem))
    base = scripts["vfx_effect"]

    lines = [BANNER, "# Sparkform effect catalogue", ""]
    lines.append(
        "Every effect ships as one scene in `addons/sparkform/effects/`. Spawn it "
        "through the `Sparkform` autoload (`Sparkform.hit_spark(...)`) and pass a "
        "dictionary of property overrides as the last argument; the generated "
        "scene is pooled, so repeated spawns do not allocate."
    )
    lines.append("")
    lines.append(
        "The tables below are generated from the `##` comments in each effect "
        "script, so they match the inspector exactly. Shared properties that "
        "every effect inherits are listed once under "
        "[shared properties](#shared-properties)."
    )
    lines.append("")

    lines.append("## Index")
    lines.append("")
    rows = []
    for effect in effects:
        spawner = spawner_for(scripts, effect.stem)
        kind = "persistent" if effect.stem in PERSISTENT else "one-shot"
        rows.append(
            [
                f"[`{effect.stem}`](#{anchor(effect.stem)})",
                code_span(spawner.get("name", "—")),
                kind,
                prose(effect.doc).split("\n")[0].split(". ")[0].rstrip(".") + ".",
            ]
        )
    lines.append(table(["Effect", "Spawner", "Kind", "Summary"], rows))
    lines.append("")

    lines.append("## Shared properties")
    lines.append("")
    lines.append(
        "Declared on `VFXEffect`, inherited by every effect scene:"
    )
    lines.append("")
    lines.extend(property_tables(base.members))
    lines.append("")

    for title, persistent in (("One-shot effects", False), ("Persistent modifiers", True)):
        lines.append(f"## {title}")
        lines.append("")
        for effect in [e for e in effects if (e.stem in PERSISTENT) == persistent]:
            lines.append(f"### {effect.stem}")
            lines.append("")
            lines.append(f'<a id="{anchor(effect.stem)}"></a>')
            lines.append("")
            lines.append(f"`{effect.class_name}`")
            lines.append("")
            spawner = spawner_for(scripts, effect.stem)
            if spawner:
                lines.append(f"Spawn with `Sparkform.{spawner['signature']}`.")
                lines.append("")
            lines.append(effect.doc or "_No description yet._")
            lines.append("")
            lines.extend(property_tables(effect.members))
            lines.append("")
            own = [f for f in effect.public_funcs()]
            if own:
                lines.append("**Methods**")
                lines.append("")
                for func in own:
                    lines.append(f"- `{func['signature']}` — {prose(func['doc'])}")
                lines.append("")
    return tidy(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the pages are stale")
    args = parser.parse_args()

    scripts = load_scripts()
    pages = {API_PAGE: build_api(scripts), EFFECTS_PAGE: build_effects(scripts)}

    stale = []
    for path, content in pages.items():
        if args.check:
            current = path.read_text(encoding="utf-8") if path.exists() else ""
            if current != content:
                stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")

    if args.check:
        for path in stale:
            print(f"out of date: {path.relative_to(ROOT)}")
        if stale:
            print("run: python3 tools/gen_docs.py")
            return 1
        print("docs are up to date")
    else:
        for path in pages:
            print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
